export type Dataset = {
  version: string;
  analysisDate: string;
  quoteDate: string;
  importedAt?: string;
  fxAt?: string;
  fxSource?: string;
  collectedAt: string;
  fx: number;
  warrantExperiment?: {
    contracts: {
      product: Product;
      quotes: {
        at: string;
        bid: number;
        ask: number;
        kind: string;
        source: string | null;
        commission: number;
        commissionPct: number;
        commissionMin: number;
      }[];
    }[];
  };
  products: Product[];
  assets: Record<string, History>;
  limits?: Record<string, string>;
  quotesCollection?: {
    at: string;
    cadence: string;
    source: string;
    universe: string[];
    observed: number;
    added: number;
    failures: { scope: string; error: string }[];
    timestamps: string;
    pagesPerAsset: number;
    maxContracts: number;
    discovered: number;
  };
  collection?: {
    failedAssets: string[];
    quoteRefresh: string;
    historySource: string;
    fx?: string;
  };
};
